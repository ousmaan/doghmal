interface LangCtx {
  lang: Lang;
  t: Dict;
  dir: "rtl" | "ltr";
  toggle: () => void;
  setLang: (l: Lang) => void;
}

const Ctx = createContext<LangCtx>({ lang: "ar", t: ar, dir: "rtl", toggle: () => {}, setLang: () => {} });

export function LanguageProvider({ children }: { children: ReactNode }) {
  // Persisted choice — mock of what the real wrapper would sync to the CRM profile
  const [lang, setLangState] = useState<Lang>(() => {
    try { return (localStorage.getItem("doghmal-lang") as Lang) || "ar"; } catch { return "ar"; }
  });
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("doghmal-lang", l); } catch { /* private mode */ }
  };
  const toggle = () => setLang(lang === "ar" ? "en" : "ar");
  useEffect(() => { document.title = lang === "ar" ? "دغمل | تويوتا نجران" : "Doghmal | Toyota Najran"; }, [lang]);
  const t = lang === "ar" ? ar : en;
  return <Ctx.Provider value={{ lang, t, dir: t.dir, toggle, setLang }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);

